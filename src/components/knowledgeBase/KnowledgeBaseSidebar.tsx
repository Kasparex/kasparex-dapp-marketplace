export function KnowledgeBaseSidebar({
  selectedCategory,
  onCategoryChange,
}: KnowledgeBaseSidebarProps) {
  const allItem = {
    id: 'all' as const,
    label: 'All Articles',
    icon: defaultIcon,
  };
  const categoryItems = [
    allItem,
    ...knowledgeBaseCategories.map((c) => ({
      id: c.id,
      label: c.name,
      icon: categoryIcons[c.id] ?? defaultIcon,
    })),
  ];

  return (
    <UnifiedSidebar
      storageKeyPrefix="kb"
      header={(onHide) => (
        <SidebarHeader
          backHref="/"
          backLabel="Back to dApps"
          onHide={onHide}
          className="bg-white dark:bg-zinc-950"
        />
      )}
      defaultWidth={280}
    >
      <SidebarCategories
        title="Categories"
        items={categoryItems}
        selectedIds={selectedCategory}
        onSelect={(id) => onCategoryChange(id as KnowledgeBaseCategory | 'all')}
        multi={false}
        collapsedItemCount={5}
      />
    </UnifiedSidebar>
  );
}
